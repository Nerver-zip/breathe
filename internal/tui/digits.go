func RenderClock(value string, fontName string) string {
	glyphMap, ok := fonts[fontName]
	if !ok {
		glyphMap = fonts[DefaultFont]
	}

	// Determine height of glyphs
	height := 6
	if g, exists := glyphMap['0']; exists && len(g) > 0 {
		height = len(g)
	}

	rows := make([]strings.Builder, height)
	for _, r := range value {
		g, ok := glyphMap[r]
		if !ok {
			continue
		}
		for i := 0; i < height && i < len(g); i++ {
			if rows[i].Len() > 0 {
				rows[i].WriteString(" ")
			}
			rows[i].WriteString(g[i])
		}
	}

	out := make([]string, height)
	for i := range rows {
		out[i] = rows[i].String()
	}
	return strings.Join(out, "\n")
}

func bigClock(value string) string {
	return RenderClock(value, FontAnsiShadow)
}
